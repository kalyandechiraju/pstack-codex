#!/usr/bin/env python3
"""Render a deterministic review report for an upstream pstack refresh."""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = "config/upstream.json"
WATCHED_PATHS = (
    "config/upstream.json",
    "vendor/cursor-plugins/pstack",
    "plugins/pstack-codex",
)


def git(*args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def config_from_text(text: str) -> dict[str, object]:
    value = json.loads(text)
    if not isinstance(value, dict):
        raise ValueError("upstream config must be a JSON object")
    return value


def current_config() -> dict[str, object]:
    return config_from_text((ROOT / CONFIG_PATH).read_text(encoding="utf-8"))


def base_config(base: str) -> dict[str, object]:
    return config_from_text(git("show", f"{base}:{CONFIG_PATH}"))


def changed_paths(base: str) -> list[tuple[str, str]]:
    output = git("diff", "--name-status", base, "--", *WATCHED_PATHS)
    changes: list[tuple[str, str]] = []
    for line in output.splitlines():
        status, path = line.split("\t", 1)
        changes.append((status, path))
    return changes


def render(base: str) -> str:
    before = base_config(base)
    after = current_config()
    changes = changed_paths(base)
    lines = [
        "# Upstream pstack compatibility report",
        "",
        "This report is generated by the scheduled upstream refresh workflow.",
        "It is deterministic so the review PR changes only when the pinned source",
        "or generated package changes.",
        "",
        "## Pin",
        "",
        "| | Previous | Refreshed |",
        "| --- | --- | --- |",
        f"| Commit | `{before.get('commit', 'unknown')}` | `{after.get('commit', 'unknown')}` |",
        f"| Version | `{before.get('version', 'unknown')}` | `{after.get('version', 'unknown')}` |",
        f"| Source | `{before.get('source', 'unknown')}` | `{after.get('source', 'unknown')}` |",
        "",
        "## Changed paths",
        "",
    ]
    if changes:
        lines.extend(f"- `{status}` `{path}`" for status, path in changes)
    else:
        lines.append("- No watched paths changed.")
    lines.extend(
        [
            "",
            "## Review checklist",
            "",
            "- Review the vendored upstream diff for intentional source changes.",
            "- Review the generated Codex diff and update the compatibility allowlist only when needed.",
            "- Confirm the plugin validator and full test suite pass before merging.",
            "- This workflow opens or updates a PR; it does not enable auto-merge.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default="HEAD", help="git revision to compare with")
    parser.add_argument(
        "--output",
        default="docs/UPSTREAM_REPORT.md",
        help="path relative to the repository root",
    )
    args = parser.parse_args()
    output = ROOT / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(args.base), encoding="utf-8")
    try:
        display_path = output.relative_to(ROOT)
    except ValueError:
        display_path = output
    print(f"wrote {display_path}")


if __name__ == "__main__":
    main()
